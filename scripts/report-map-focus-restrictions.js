// Read-only data audit for the "View on map" focus-mode location matching
// (see src/utils/dealHelpers.js: matchLocationsToRestriction / getMapFocusLocations).
// Writes reports/map-focus-restrictions-report.md. Does not modify deals.json.
import { writeFileSync } from 'node:fs'
import dealsData from '../src/data/deals.json' with { type: 'json' }
import {
  BROAD_RESTRICTION,
  splitRestrictionClauses,
  expandPlaceTokens,
  cityFromAddress,
  matchLocationsToRestriction,
} from '../src/utils/dealHelpers.js'

const restricted = dealsData.filter(d => d.locationRestriction)

// --- Exclusion wording count ---
const EXCLUSION_RE = /\b(excl\.?|exclude[sd]?|except|not)\b/i
const withExclusion = restricted.filter(d => EXCLUSION_RE.test(d.locationRestriction))

// --- Per-deal resolution using the real matching logic ---
const rows = restricted.map(d => {
  const restriction = d.locationRestriction.trim()
  const { includeText } = splitRestrictionClauses(restriction)
  const isBroad = BROAD_RESTRICTION.test(includeText.trim())
  const matched = matchLocationsToRestriction(d.locations, restriction)
  const matchedCities = matched ? [...new Set(matched.map(l => cityFromAddress(l.address)))] : []
  return {
    id: d.id, name: d.name, restriction, isBroad,
    hasExclusion: EXCLUSION_RE.test(restriction),
    totalLocs: d.locations.length,
    matched, matchedCount: matched?.length ?? 0, matchedCities,
    allCities: [...new Set(d.locations.map(l => cityFromAddress(l.address)))],
  }
})

const hidden = rows.filter(r => !r.matched)

// --- Partial matches: specific (non-broad), 2+ include tokens, at least one token unmatched ---
const partial = []
rows.filter(r => !r.isBroad && r.matched).forEach(r => {
  const { includeText } = splitRestrictionClauses(r.restriction)
  const tokens = expandPlaceTokens(includeText)
  if (tokens.length < 2) return
  const unmatchedTokens = tokens.filter(tok =>
    !r.matched.some(l => {
      const city = cityFromAddress(l.address)
      const c = (city || '').toLowerCase()
      return c && (c.includes(tok) || tok.includes(c))
    })
  )
  if (unmatchedTokens.length > 0) {
    partial.push({ ...r, tokens, unmatchedTokens })
  }
})

// --- Blank top-level address, among restricted deals ---
const blankTopAddress = restricted.filter(d => !d.address)

// --- Top-level address/lat-lng vs restriction mismatch (excluding blank-address ones) ---
const topLevelMismatches = restricted
  .filter(d => d.address)
  .map(d => {
    const singleton = [{ lat: d.lat, lng: d.lng, address: d.address }]
    const result = matchLocationsToRestriction(singleton, d.locationRestriction)
    return { id: d.id, name: d.name, restriction: d.locationRestriction, address: d.address, city: cityFromAddress(d.address), ok: !!result }
  })
  .filter(r => !r.ok)

// --- Jersey Mike's exclusion resolution detail ---
const jerseyMikes = rows.filter(r => r.name === "Jersey Mikes" && r.hasExclusion)

const lines = []
lines.push('# View on Map — Restriction Matching Data Audit')
lines.push('')
lines.push('Generated by `scripts/report-map-focus-restrictions.js` against `src/data/deals.json`.')
lines.push('Read-only — no data files were changed. Reflects the matching logic in')
lines.push('`src/utils/dealHelpers.js` (`matchLocationsToRestriction` / `getMapFocusLocations`)')
lines.push("exactly, so this report and the app's actual behavior can't drift apart.")
lines.push('')
lines.push('## Summary')
lines.push('')
lines.push(`- ${restricted.length} deals have a \`locationRestriction\``)
lines.push(`- ${rows.filter(r => r.isBroad).length} are broad wording (All / county-level / Participating / Same Locations / "Northern UT") — full \`locations[]\` shown, minus any exclusions`)
lines.push(`- ${rows.length - rows.filter(r => r.isBroad).length} name specific place(s) — filtered to matching cities`)
lines.push(`- ${withExclusion.length} restrictions contain exclusion wording ("excl.", "except", "not") — see below`)
lines.push(`- ${hidden.length} deals resolve to **zero locations** — "View on map" is hidden for these`)
lines.push(`- ${partial.length} deals are **partial matches** — restriction names multiple places, at least one matched no location`)
lines.push(`- ${blankTopAddress.length} restricted deals have a blank top-level \`address\` field`)
lines.push('')
lines.push('## Does the top-level `lat`/`lng`/`address` drive anything outside focus mode?')
lines.push('')
lines.push('**No effect on map pins or "Nearest" sorting.** Checked directly against the code:')
lines.push('')
lines.push('- `MapView.jsx` pins: always built from `deal.locations[]`; the top-level-lat/lng fallback path only')
lines.push('  runs when a deal has zero `locations[]` entries, and every deal in `deals.json` has at least one — so')
lines.push('  that fallback is dead code in practice.')
lines.push('- `getNearestDistance` / `getNearestLocation` (used for the "Nearest" sort and any on-screen distance')
lines.push('  label) also read exclusively from `deal.locations[]`, never the top-level fields.')
lines.push('')
lines.push('**It does drive one real, user-facing thing:** the "Get Directions" Google Maps link and address text')
lines.push('shown on the deal detail screen (`BottomSheet.jsx`, `DealModal.jsx`) use `deal.lat`/`deal.lng`/`deal.address`')
lines.push("directly. For a deal opened from the Home tab (the normal path — these fields aren't overridden the way a")
lines.push('map-pin tap overrides them), a wrong top-level address means the existing "Get Directions" link — not just')
lines.push('"View on map" — could send someone to a location that doesn\'t honor the deal. See the mismatch list below.')
lines.push('')
lines.push('## Exclusion wording (Approved change #1)')
lines.push('')
lines.push(`${withExclusion.length} of ${restricted.length} restrictions contain exclusion wording, all on the same business:`)
lines.push('')
withExclusion.forEach(d => lines.push(`- \`${d.id}\` ${d.name} — "${d.locationRestriction}"`))
lines.push('')
lines.push('Resolution with the new exclusion-aware matching:')
lines.push('')
jerseyMikes.forEach(r => lines.push(`- \`${r.id}\` — "${r.restriction}" → broad scope (${r.totalLocs} locations) minus excluded city/cities → **${r.matchedCount} locations shown**: ${r.matchedCities.join(', ')}`))
lines.push('')
lines.push("(Spanish Fork is correctly dropped; there's no Eagle Mountain location in this business's `locations[]` to begin with, so only the SF exclusion actually changes anything.)")
lines.push('')
lines.push(`## Hidden deals — resolve to zero locations (${hidden.length})`)
lines.push('')
lines.push('"View on map" does not render for these; no pin can be shown with confidence.')
lines.push('')
lines.push('| Deal | Business | Restriction | Location cities on file |')
lines.push('|---|---|---|---|')
hidden.forEach(r => lines.push(`| \`${r.id}\` | ${r.name} | "${r.restriction}" | ${r.allCities.filter(Boolean).join(', ') || '*(blank)*'} |`))
lines.push('')
lines.push(`## Partial matches — some named place(s) matched, others didn't (${partial.length})`)
lines.push('')
lines.push('Still shown (whatever did match), flagged here for visibility — restriction names 2+ places but at least')
lines.push('one has no matching location on file.')
lines.push('')
lines.push('| Deal | Business | Restriction | Matched | Unmatched place(s) |')
lines.push('|---|---|---|---|---|')
partial.forEach(r => lines.push(`| \`${r.id}\` | ${r.name} | "${r.restriction}" | ${r.matchedCities.join(', ')} | ${r.unmatchedTokens.join(', ')} |`))
lines.push('')
lines.push(`## Blank top-level address (${blankTopAddress.length})`)
lines.push('')
lines.push('These restricted deals have no top-level `address` string at all (lat/lng still present). Doesn\'t block')
lines.push('`getMapFocusLocations` — it works from `locations[].address`, not the top-level field — but it does mean')
lines.push('the "Get Directions" link and address line on the deal detail screen show nothing/blank for these when')
lines.push('opened from Home.')
lines.push('')
lines.push('| Deal | Business | Restriction |')
lines.push('|---|---|---|')
blankTopAddress.forEach(d => lines.push(`| \`${d.id}\` | ${d.name} | "${d.locationRestriction}" |`))
lines.push('')
lines.push(`## Top-level address falls outside its own restriction (${topLevelMismatches.length})`)
lines.push('')
lines.push('Every restricted deal with a non-blank top-level address, checked with the same matching logic used for')
lines.push('`locations[]`. These are cases where `deal.address`/`deal.lat`/`deal.lng` (the "Get Directions" link')
lines.push('target) is itself not in a restriction-honoring city — independent of `locations[]` or "View on map".')
lines.push('')
lines.push('| Deal | Business | Restriction | Top-level address | City |')
lines.push('|---|---|---|---|---|')
topLevelMismatches.forEach(r => lines.push(`| \`${r.id}\` | ${r.name} | "${r.restriction}" | ${r.address} | ${r.city} |`))
lines.push('')

const md = lines.join('\n')
writeFileSync(new URL('../reports/map-focus-restrictions-report.md', import.meta.url), md)
console.log('Wrote reports/map-focus-restrictions-report.md')
console.log(`Restricted: ${restricted.length} | Broad: ${rows.filter(r => r.isBroad).length} | Specific: ${rows.length - rows.filter(r => r.isBroad).length}`)
console.log(`Exclusion wording: ${withExclusion.length}`)
console.log(`Hidden (zero match): ${hidden.length}`)
console.log(`Partial matches: ${partial.length}`)
console.log(`Blank top-level address: ${blankTopAddress.length}`)
console.log(`Top-level address outside restriction: ${topLevelMismatches.length}`)
